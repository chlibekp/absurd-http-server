#!/usr/bin/env python3
"""Generates src/common/gen.s: the JS challenge page and the character-class table.

    python3 tools/gen.py      # run from the repository root after editing tools/challenge.js
"""
import os, string
here = os.path.dirname(os.path.abspath(__file__))
js = open(os.path.join(here, "challenge.js")).read().strip()
assert js.count("__NONCE__") == 1 and "\\" not in js
head, tail = js.split("__NONCE__")

page1 = ('<!doctype html><html lang="en"><head><meta charset="utf-8">'
         '<meta name="viewport" content="width=device-width,initial-scale=1">'
         '<meta name="robots" content="noindex,nofollow"><title>One moment</title>'
         '<style>body{font:16px/1.5 system-ui,sans-serif;margin:0;min-height:100vh;display:flex;'
         'align-items:center;justify-content:center;background:#fafafa;color:#222}main{max-width:32em;padding:1em}'
         '@media(prefers-color-scheme:dark){body{background:#111;color:#ddd}}</style></head><body><main>'
         '<h1>Checking your browser</h1><p>This site is protected against automated traffic. '
         'The page continues on its own in a moment.</p><noscript><p><b>JavaScript and cookies are '
         'required to continue.</b></p></noscript></main><script>') + head
page2 = tail + "</script></body></html>\n"

def ascii_lines(label, s):
    out = [f"{label}:"]
    for i in range(0, len(s), 100):
        part = s[i:i + 100].replace('"', '\\"')
        out.append(f'        .ascii  "{part}"')
    out.append(f"{label}_end:")
    return "\n".join(out)

TCHAR, PATH, QUERY, HOST, HEX = 1, 2, 4, 8, 16
cls = [0] * 256
unreserved = string.ascii_letters + string.digits + "-._~"
subdelims = "!$&'()*+,;="
for c in string.ascii_letters + string.digits + "!#$%&'*+-.^_`|~": cls[ord(c)] |= TCHAR
for c in unreserved + subdelims + ":@/": cls[ord(c)] |= PATH | QUERY
cls[ord("?")] |= QUERY
for c in unreserved + subdelims + ":[]%": cls[ord(c)] |= HOST
for c in string.hexdigits: cls[ord(c)] |= HEX

with open(os.path.join(here, "..", "src", "common", "gen.s"), "w") as f:
    f.write("// Generated by tools/gen.py -- do not edit.\n        .section .rodata\n")
    f.write(f"        .equ CC_TCHAR, {TCHAR}\n        .equ CC_PATH, {PATH}\n        .equ CC_QUERY, {QUERY}\n"
            f"        .equ CC_HOST, {HOST}\n        .equ CC_HEX, {HEX}\n")
    f.write("        .p2align 4\nt_class:\n")
    for i in range(0, 256, 16):
        f.write("        .byte   " + ", ".join(str(v) for v in cls[i:i + 16]) + "\n")
    f.write(ascii_lines("s_chal1", page1) + "\n" + ascii_lines("s_chal2", page2) + "\n")
print("wrote src/common/gen.s", len(page1) + len(page2) + 26, "byte challenge page")
